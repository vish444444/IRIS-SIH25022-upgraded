"""
train_model.py
================
Trains a Gradient Boosting Regressor to predict `future_delay_min` from
the SYNTHETIC dataset produced by data/generate_dataset.py.

This is real, executable ML training -- not a stub. It:
  1. Generates (or loads) the synthetic dataset
  2. Splits train/test
  3. Trains a scikit-learn GradientBoostingRegressor
  4. Evaluates with MAE / RMSE / R^2 on a held-out test set
  5. Saves the model + feature list + metrics to ai-service/models/

Model choice: GradientBoostingRegressor (sklearn) was chosen over
XGBoost/LightGBM to avoid an extra native-library dependency in the
hackathon demo environment, while still being a boosted-tree model
that is fast to train, easy to explain (feature_importances_), and
directly comparable in behaviour to XGBoost for this use case.

Usage:
    python train_model.py --rows 8000
"""
import argparse
import json
import os
import sys
import time

import joblib
import numpy as np
import pandas as pd
from sklearn.ensemble import GradientBoostingRegressor
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
from sklearn.model_selection import train_test_split

sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from data.generate_dataset import generate_dataset, FEATURE_COLUMNS, TARGET_COLUMN  # noqa: E402

THIS_DIR = os.path.dirname(os.path.abspath(__file__))
MODELS_DIR = os.path.join(os.path.dirname(THIS_DIR), "models")
os.makedirs(MODELS_DIR, exist_ok=True)


def train(n_rows: int, seed: int = 42):
    print(f"[train_model] Generating {n_rows} SYNTHETIC rows (seed={seed})...")
    df = generate_dataset(n_rows, seed)

    X = df[FEATURE_COLUMNS]
    y = df[TARGET_COLUMN]

    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.2, random_state=seed
    )

    model = GradientBoostingRegressor(
        n_estimators=200,
        max_depth=4,
        learning_rate=0.08,
        random_state=seed,
    )

    t0 = time.time()
    model.fit(X_train, y_train)
    train_seconds = time.time() - t0

    preds = model.predict(X_test)
    mae = mean_absolute_error(y_test, preds)
    rmse = float(np.sqrt(mean_squared_error(y_test, preds)))
    r2 = r2_score(y_test, preds)

    metrics = {
        "model_type": "GradientBoostingRegressor",
        "n_rows": n_rows,
        "n_train": len(X_train),
        "n_test": len(X_test),
        "train_seconds": round(train_seconds, 3),
        "MAE_minutes": round(float(mae), 4),
        "RMSE_minutes": round(float(rmse), 4),
        "R2": round(float(r2), 4),
        "feature_importances": {
            col: round(float(imp), 4)
            for col, imp in zip(FEATURE_COLUMNS, model.feature_importances_)
        },
        "note": "Trained and evaluated on SYNTHETIC data generated by data/generate_dataset.py. Not real Indian Railways data.",
    }

    model_path = os.path.join(MODELS_DIR, "delay_model.joblib")
    metrics_path = os.path.join(MODELS_DIR, "metrics.json")
    features_path = os.path.join(MODELS_DIR, "feature_columns.json")

    joblib.dump(model, model_path)
    with open(metrics_path, "w") as f:
        json.dump(metrics, f, indent=2)
    with open(features_path, "w") as f:
        json.dump(FEATURE_COLUMNS, f, indent=2)

    print(f"[train_model] Saved model to {model_path}")
    print(f"[train_model] MAE={mae:.3f} min  RMSE={rmse:.3f} min  R2={r2:.3f}")
    return metrics


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--rows", type=int, default=8000)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()
    train(args.rows, args.seed)
